#!/usr/bin/env node
/**
 * Extract canon's player-facing message strings from MBMGEMSG.MSG.
 *
 * The port rewrote canon's in-world voice into flat modern UI text — "Warp
 * Drive? On this tub? Sorry Sir!" became "Your ship has no warp drive." A sweep
 * found only 26 of our 325 strings matching canon and 108 differing. The voice
 * is not decoration; it is most of what the game feels like.
 *
 * Generated rather than hand-copied, for the same reason the ship table and the
 * help pages are. @see tools/extract-ship-classes.mjs, tools/extract-help.mjs
 *
 * Usage: node tools/extract-messages.mjs --ts > backend/src/game/commands/canon-messages.generated.ts
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
export const MSG_PATH = join(here, '..', 'reference', 'ge-upstream', 'mbmgemp', 'GE', 'REL', 'MBMGEMSG.MSG');

const stripAnsi = (s) => s.replace(/\x1b?\[[0-9;]*[A-Za-z]/g, '');

export function extractMessages(rawIn = readFileSync(MSG_PATH, 'latin1')) {
  const raw = stripAnsi(rawIn);
  const out = new Map();
  // `ID {text}` closed by a brace and a type letter (T, N, B ...). The brace is
  // NOT always at the start of a line: canon writes short strings inline, e.g.
  // `SCAN11 {Environment:} T`. Anchoring the terminator to a line start made
  // every inline entry swallow forward to its neighbour's terminator — SCAN11
  // ate SCAN12 — while still producing a plausible-looking 784 entries. Same
  // trap the help extractor fell into with `ESC[0m} T`.
  // The body may not contain a brace, which forces the FIRST closing brace to
  // terminate the entry. Anything looser runs away: anchoring the brace to a
  // line start let inline entries swallow their neighbour (SCAN11 ate SCAN12),
  // and requiring a newline after the type letter let entries whose terminator
  // carries a trailing comment do the same (`} T spy Wormhole Message` — SPY0B
  // ate SPY0C). Both produced a plausible-looking table with silent holes.
  const re = /^([A-Z][A-Z0-9_]*)[ \t]*\{([^{}]*?)\}[ \t]*[A-Z]/gm;
  let m;
  while ((m = re.exec(raw)) !== null) {
    out.set(m[1], m[2].replace(/[ \t]+$/gm, '').replace(/\n+$/, ''));
  }
  return out;
}

if (process.argv.includes('--ts')) {
  const msgs = extractMessages();
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
  console.log(`/**
 * GENERATED by tools/extract-messages.mjs — do not edit by hand.
 *
 * Canon's message strings, verbatim from GE/REL/MBMGEMSG.MSG (release 3.2e),
 * ANSI colour stripped. ${msgs.size} entries.
 *
 * Canon's printf specifiers are preserved as written (%s, %d, %u), which
 * formatMessage already substitutes positionally.
 *
 * @see test/balance/message-canon.balance.spec.ts — re-reads the original
 */
export const CANON_MESSAGES: Readonly<Record<string, string>> = Object.freeze({`);
  for (const [id, text] of msgs) console.log(`  ${id}: '${esc(text)}',`);
  console.log('});');
}
