#!/usr/bin/env node
/**
 * Extract the per-class "Detailed Class Specification" pages from the original
 * MBMGESHP.MSG.
 *
 * Canon's `HELP CLASS nn` prints `shipclass[i].hlpmsg` (GECMDS.C:438-446),
 * which GEMAIN.C:871 binds by READ ORDER to the `S<nn>HELP` block of each
 * class. The pages carry detail the summary table cannot: mission profile,
 * hull dimensions, and the standard-versus-maximum fit for shields and phasers.
 *
 * Generated rather than transcribed, per the project rule, and pinned by
 * test/balance/class-help-canon.balance.spec.ts which re-reads this same file.
 *
 * Usage: node tools/extract-class-help.mjs [--ts]
 *
 * @see reference/ge-upstream/PROVENANCE.md
 * @see GECMDS.C:438 the margc == 3 branch
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(HERE, '../reference/ge-upstream/mbmgemp/GE/REL/MBMGESHP.MSG')
const OUT = resolve(HERE, '../backend/src/game/commands/help/class-help.generated.ts')

/** Strip the ANSI colour and clear-screen codes canon embeds in its pages. */
const stripAnsi = (s) => s.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')

export function extractClassHelp(text) {
  const out = new Map()
  // The terminator is the brace followed by the option's own condition —
  // `} (S01TYPE#<NONE>) T`. Anchoring on `^\}` instead looked safe and was not:
  // class 5's page is TRUNCATED in canon, closing mid-line as
  // `Price:          }` with the value missing, so an anchored match ran past
  // it and swallowed classes 6 and 7 whole.
  const re = /^S(\d+)HELP \{([\s\S]*?)\}\s*\(S\d+TYPE#/gm
  let m
  while ((m = re.exec(text)) !== null) {
    const classNumber = Number(m[1])
    const body = stripAnsi(m[2])
      .split('\n')
      .map((l) => l.replace(/\s+$/, ''))
      // Canon opens every page with a bare `***` separator, which the port
      // renders as its own line elsewhere and does not want inside the body.
      .filter((l, i) => !(i === 0 && l.trim() === '***'))
    while (body.length && body[body.length - 1].trim() === '') body.pop()
    while (body.length && body[0].trim() === '') body.shift()
    if (body.length) out.set(classNumber, body)
  }
  return out
}

const pages = extractClassHelp(readFileSync(SRC, 'latin1'))
if (pages.size === 0) throw new Error('no S<nn>HELP blocks found — has the source moved?')

if (process.argv.includes('--ts')) {
  const entries = [...pages.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([n, lines]) => `  ${n}: [\n${lines.map((l) => `    ${JSON.stringify(l)},`).join('\n')}\n  ],`)
    .join('\n')
  writeFileSync(OUT, `/**
 * GENERATED by tools/extract-class-help.mjs — do not edit by hand.
 *
 * Canon's per-class detail pages, verbatim from GE/REL/MBMGESHP.MSG
 * (release 3.2e), ANSI stripped. ${pages.size} entries, keyed by class number.
 *
 * \`HELP CLASS nn\` prints \`shipclass[i].hlpmsg\` (GECMDS.C:438-446); GEMAIN.C:871
 * binds that field to the class's S<nn>HELP block by read order.
 *
 * @see test/balance/class-help-canon.balance.spec.ts — re-reads the original
 */
export const CLASS_HELP: Readonly<Record<number, readonly string[]>> = Object.freeze({
${entries}
});
`)
  console.error(`wrote ${pages.size} class pages -> ${OUT}`)
} else {
  console.log(JSON.stringify(Object.fromEntries(pages), null, 2))
}
